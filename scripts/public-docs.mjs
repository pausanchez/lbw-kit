// scripts/public-docs.mjs · the public AGENTS.md and llms.txt, made from the private ones.
//   node scripts/public-docs.mjs          write .github/AGENTS.md and .github/llms.txt
//   node scripts/public-docs.mjs --check  change nothing; exit 1 when they are stale
// The private AGENTS.md and llms.txt (repo root, not tracked here) name clients and link private folders, so the default is
// SAFE: nothing is public unless marked.
//   <!-- public --> … <!-- /public -->        a block that may go public
//   <!-- private --> … <!-- /private -->      inside a public block: dropped from the public copy (a link to docs/, a client)
//   <!-- public-only … -->                    text that exists only in the public copy
// A last guard refuses to write when the result still names a client, a "reto N", or a private path.
import fs from 'node:fs';

const root = new URL('..', import.meta.url);
const check = process.argv.includes('--check');
const BLOB = 'https://github.com/pausanchez/lbw-kit/blob/main/';
// What may not reach a public file: the client names (the folder names under examples/, and tools/private-denylist.txt when
// there is one: plain lines, "re:" lines skipped here), "reto N", "blind build", and the private folders' paths.
const names = [];
try { for (const d of fs.readdirSync(new URL('examples/', root))) if (d !== 'starter') names.push(...d.split('-').filter((w) => w.length > 3 && w !== 'port')); } catch (e) {}
try { names.push(...fs.readFileSync(new URL('tools/private-denylist.txt', root), 'utf8').split('\n').filter((l) => !l.trim().startsWith('#')).join('\n').split(/[\n,]/).map((x) => x.trim()).filter((x) => x && !x.startsWith('re:'))); } catch (e) {}
const esc = (x) => x.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const FORBIDDEN = new RegExp([...names.map(esc), '\\bretos? ?\\d+', 'blind build', '\\b(?:docs|examples|tools)/'].join('|'), 'i');
const files = [['AGENTS.md', '.github/AGENTS.md'], ['llms.txt', '.github/llms.txt']];

if (!files.every(([src]) => fs.existsSync(new URL(src, root)))) { console.log('skipped: private sources not present'); process.exit(0); }

function pub(src) {
  const text = fs.readFileSync(new URL(src, root), 'utf8');
  const re = /<!-- public -->\n([\s\S]*?)<!-- \/public -->\n?|<!-- public-only\n([\s\S]*?)-->\n?/g;
  let out = '', m;
  while ((m = re.exec(text))) out += (m[1] ?? m[2]).replace(/ ?<!-- private -->[\s\S]*?<!-- \/private -->/g, '').trimEnd() + '\n\n';
  out = out.replace(/\]\((?!https?:|#|\.\.)([^)]+)\)/g, (_, p) => `](${BLOB}${p})`).replace(/\n{3,}/g, '\n\n').trim() + '\n';
  return `<!-- Generated by scripts/public-docs.mjs from the private ${src}: edit that, then run npm run docs:public. -->\n` + out;
}

let stale = 0;
for (const [src, dest] of files) {
  const out = pub(src), bad = FORBIDDEN.exec(out);
  if (bad) { console.error(`${dest}: would name "${bad[0]}" (a private name or path): mark it <!-- private --> in ${src}`); process.exit(2); }
  const url = new URL(dest, root);
  const now = fs.existsSync(url) ? fs.readFileSync(url, 'utf8') : '';
  if (now === out) continue;
  stale++;
  if (check) console.error(`${dest}: stale (run npm run docs:public)`);
  else { fs.writeFileSync(url, out); console.log(`${dest} written`); }
}
if (check && stale) process.exit(1);
console.log(check ? 'public docs up to date' : `public docs: ${stale} file${stale === 1 ? '' : 's'} changed`);
